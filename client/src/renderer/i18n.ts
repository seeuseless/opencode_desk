const DICTS: Record<Lang, Record<string, string> | null> = { zh: null, tw: TW, en: EN }

const stored = load<Lang>('qingniao.lang', 'zh')
let cur: Lang = stored === 'tw' || stored === 'en' ? stored : 'zh'

export function getLang(): Lang {
  return cur
}

/** 切换语言并持久化；App 持有语言状态驱动重渲染，这里只落模块变量与存档 */
export function setLang(l: Lang): void {
  cur = l
  save('qingniao.lang', l)
}

/** 取当前语言的文案；{x} 占位符用 params 替换（不传 params 时不做替换，键里的 {x} 原样保留） */
export function t(key: string, params?: Record<string, string | number>): string {
  let s = (cur !== 'zh' ? DICTS[cur]?.[key] : undefined) ?? key
  if (params) for (const k in params) s = s.split(`{${k}}`).join(String(params[k]))
  return s
}
